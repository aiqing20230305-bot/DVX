export function buildScriptUserMessage(
  topicData: string,
  variant: 'A' | 'B',
  brandContext?: string
): string {
  const variantGuide = variant === 'A'
    ? `【A版本：情感驱动型】
重点：强情绪共鸣、具体生活场景、痛点代入感强
Hook策略：优先用问题崩塌型或理发店反转型
节奏：情绪铺垫更长（3-10s），转化收口要温和
CTA：用理解式语气（"如果你也..."）`
    : `【B版本：理性驱动型】
重点：数据背书、成分/特证、性价比锚点、套组逻辑
Hook策略：优先用值感反差型或测评对比型
节奏：卖点输出更集中（直接在10s内完成产品介绍）
CTA：用认知升级语气（"发膜这种东西，真别按一次买"）`

  return `为以下选题创作${variant}版本投流脚本。

${variantGuide}

${brandContext ? `【品牌信息】\n${brandContext}\n` : ''}

【选题信息】
${topicData}

用<script>标签包裹完整JSON脚本。确保：
1. 口播文案完整（fullVoiceover字段）
2. 每个segment都有具体镜头描述（shot字段）
3. 混剪策略完整（mixCutStrategy字段含素材池/镜头顺序/字幕节奏）
4. A/B版本形成明显差异化`
}
